import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fas } from '@fortawesome/free-solid-svg-icons';
import { far } from '@fortawesome/free-regular-svg-icons';
import { fab } from '@fortawesome/free-brands-svg-icons';

type SourceIcon = {
  iconName: string;
  icon: [number, number, unknown, string, string | string[]];
};
type GeneratedIcon = [id: string, name: string, svg: string, collection: string];

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const rows: GeneratedIcon[] = [];
const seen = new Set<string>();

function add(row: GeneratedIcon): void {
  if (seen.has(row[0])) throw new Error(`Duplicate icon ID: ${row[0]}`);
  seen.add(row[0]);
  rows.push(row);
}

function escapeAttribute(value: string): string {
  return value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;');
}

for (const [collection, pack] of [
  ['fa-solid', fas],
  ['fa-regular', far],
  ['fa-brands', fab],
] as const) {
  // The package dictionaries contain aliases; iconName is the stable canonical ID.
  const icons = new Map<string, SourceIcon>();
  for (const value of Object.values(pack) as SourceIcon[]) icons.set(value.iconName, value);
  for (const name of [...icons.keys()].sort()) {
    const definition = icons.get(name)!;
    const [width, height, , , rawPaths] = definition.icon;
    const paths = Array.isArray(rawPaths) ? rawPaths : [rawPaths];
    const pathTags = paths.map((path) => `<path d="${escapeAttribute(path)}"/>`).join('');
    add([`${collection}/${name}`, name, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" fill="currentColor">${pathTags}</svg>`, collection]);
  }
}

const remixRoot = join(root, 'node_modules', 'remixicon', 'icons');
for (const directory of readdirSync(remixRoot, { withFileTypes: true }).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort()) {
  for (const file of readdirSync(join(remixRoot, directory)).filter((entry) => entry.endsWith('.svg')).sort()) {
    const name = file.slice(0, -4);
    if (!/^[a-z0-9-]+$/.test(name)) throw new Error(`Invalid Remix icon name: ${file}`);
    const source = readFileSync(join(remixRoot, directory, file), 'utf8').trim();
    const outer = source.match(/^<svg viewBox="([\d\s.]+)" fill="currentColor" xmlns="http:\/\/www\.w3\.org\/2000\/svg">([\s\S]*)<\/svg>$/);
    if (!outer) throw new Error(`Unexpected Remix SVG shape: ${file}`);
    const inner = outer[2];
    // Remix 4.7.0 includes two logos with a literal fill; normalize to currentColor.
    const paths = [...inner.matchAll(/<path d="([^"]*)"(?: fill="#[0-9a-fA-F]{6}")?\s*\/>/g)];
    if (paths.length === 0 || paths.map((match) => match[0]).join('') !== inner) {
      throw new Error(`Unexpected Remix SVG content: ${file}`);
    }
    const pathTags = paths.map((match) => `<path d="${escapeAttribute(match[1])}"/>`).join('');
    add([`remix/${name}`, name, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${outer[1]}" fill="currentColor">${pathTags}</svg>`, 'remix']);
  }
}

rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
const destination = join(root, 'src', 'generated', 'icons.ts');
mkdirSync(dirname(destination), { recursive: true });
writeFileSync(destination, `// Generated by npm run generate from pinned local icon packages. Do not edit.\nexport const icons: readonly (readonly [string, string, string, string])[] = ${JSON.stringify(rows)};\n`, 'utf8');
console.log(`Generated ${rows.length} icon records`);
